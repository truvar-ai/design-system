// Writes src/core/country-names.js: every country's English and Arabic name, and both alphabetical orders.
// Names are frozen here instead of read from Intl.DisplayNames at runtime, because Node and each browser ship
// different CLDR versions: live names differed between the server and the browser and broke hydration in Next.js.
// Run again (pnpm build:countries) to pick up newer names.
import fs from "fs";
import { getCountries } from "libphonenumber-js/max";

const names = (locale) => { const dn = new Intl.DisplayNames([locale], { type: "region" }); return (c) => { try { return dn.of(c) ?? c; } catch { return c; } }; };
const en = names("en"), ar = names("ar");
const codes = getCountries();
const NAMES = Object.fromEntries(codes.map((c) => [c, [en(c), ar(c)]]));
const order = (i, locale) => [...codes].sort((a, b) => NAMES[a][i].localeCompare(NAMES[b][i], locale));
const out = `// Generated by scripts/build-countries.mjs from CLDR (Node ${process.versions.node}, ICU ${process.versions.icu}). Do not edit.
export const NAMES = ${JSON.stringify(NAMES)};
export const ORDER = { en: ${JSON.stringify(order(0, "en"))}, ar: ${JSON.stringify(order(1, "ar"))} };
`;
fs.writeFileSync("./src/core/country-names.js", out);
console.log("countries", codes.length, "bytes", out.length);
