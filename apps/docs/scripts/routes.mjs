// Before `next dev` and `next build`: writes one route per component page, in both languages
// (app/(en)/docs/<id>/page.jsx and app/(ar)/ar/docs/<id>/page.jsx). With its own route, each page
// renders its live example into its HTML in place and loads only that example's code in the browser.
// The written guides stay on app/.../docs/[slug]. The generated folders are listed in .gitignore.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { VIEW_SOURCES } from "../src/docs/view-sources.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.join(HERE, "../app");
const SHOWCASE = path.join(HERE, "../../showcase/src");
const DIST = path.join(HERE, "../../../packages/design-system/dist");

/* Which package stylesheets a page needs: the package modules its view file uses, following the
   showcase's own local imports. Pages then load only their own CSS instead of every module's. */
const MODULES = ["charts", "voice", "os", "crm", "widget"];
const exportsOf = (mod) => {
  const src = fs.readFileSync(path.join(DIST, `${mod}.js`), "utf8");
  const list = [...src.matchAll(/export\s*\{([^}]*)\}/g)].flatMap((m) => m[1].split(","));
  return new Set(list.map((x) => x.trim().split(/\s+as\s+/).pop()).filter(Boolean));
};
const MODULE_EXPORTS = Object.fromEntries(MODULES.map((m) => [m, exportsOf(m)]));
function modulesUsed(file, seen = new Set()) {
  if (seen.has(file)) return new Set();
  seen.add(file);
  const src = fs.readFileSync(file, "utf8");
  const used = new Set();
  for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*"([^"]+)"/g)) {
    const [names, from] = [m[1].split(",").map((x) => x.trim().split(/\s+as\s+/)[0]).filter(Boolean), m[2]];
    const direct = from.match(/^@truvar-ai\/design-system\/(\w+)$/);
    if (direct && MODULES.includes(direct[1])) used.add(direct[1]);
    if (from.endsWith("ds.js")) for (const n of names) for (const mod of MODULES) if (MODULE_EXPORTS[mod].has(n)) used.add(mod);
    if (from.startsWith(".") && !from.endsWith("ds.js") && /\.jsx?$/.test(from)) for (const x of modulesUsed(path.join(path.dirname(file), from), seen)) used.add(x);
  }
  return used;
}
const ROOTS = { en: "(en)/docs", ar: "(ar)/ar/docs" };
const MARK = "// Generated by scripts/routes.mjs. Do not edit.";

let n = 0;
for (const [lang, base] of Object.entries(ROOTS)) {
  const dir = path.join(APP, base);
  // Remove routes from earlier runs, so a page taken out of view-sources.js disappears too
  for (const d of fs.readdirSync(dir)) {
    const f = path.join(dir, d, "page.jsx");
    if (fs.existsSync(f) && fs.readFileSync(f, "utf8").startsWith(MARK)) fs.rmSync(path.join(dir, d), { recursive: true });
  }
  for (const [id, [file, name]] of Object.entries(VIEW_SOURCES)) {
    const out = path.join(dir, id);
    const src = path.relative(out, path.join(APP, "../src")).split(path.sep).join("/");
    const css = [...modulesUsed(path.join(SHOWCASE, "docs/views", `${file}.jsx`))].sort()
      .map((m) => `import "@truvar-ai/design-system/${m}/styles.css";`).concat('import "showcase/src/demos.css";').join("\n");
    const view = name === "default" ? `import View from "showcase/src/docs/views/${file}.jsx";` : `import { ${name} as View } from "showcase/src/docs/views/${file}.jsx";`;
    fs.mkdirSync(out, { recursive: true });
    fs.writeFileSync(path.join(out, "page.jsx"), `${MARK}
${css}
${view}
import { DocPage } from "${src}/docs/DocPage.jsx";
import { docMeta, docJsonLd } from "${src}/site/meta.js";
import { JsonLd } from "${src}/site/JsonLd.jsx";

export const metadata = docMeta("${lang}", "${id}");
export default function Page() {
  return <><JsonLd data={docJsonLd("${lang}", "${id}")} /><DocPage id="${id}"><View /></DocPage></>;
}
`);
    n++;
  }
}
console.log(`routes: ${n} component pages`);
